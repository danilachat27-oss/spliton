function md(title: string, sections: Array<[string, string]>): string {
  const body = sections.map(([h, p]) => `## ${h}\n\n${p}`).join('\n\n');
  return `# ${title}\n\nПоследнее обновление: июнь 2026\n\n${body}`;
}

