export const SUPPORT_TICKET_CATEGORY_VALUES = [
  "deposit",
  "withdrawal",
  "wallet",
  "primary_purchase",
  "secondary_market",
  "payouts",
  "account",
  "technical",
  "other",
] as const;

export type SupportTicketCategoryValue = (typeof SUPPORT_TICKET_CATEGORY_VALUES)[number];

export function supportTicketCategoryLabel(
  category: string,
  _locale: AppLocale,
): string {
  const RU: Record<SupportTicketCategoryValue, string> = {
    deposit: "Пополнение",
    withdrawal: "Вывод",
    wallet: "Кошелёк",
    primary_purchase: "Покупка юнитов",
    secondary_market: "Вторичный рынок",
    payouts: "Начисления",
    account: "Аккаунт",
    technical: "Техническая проблема",
    other: "Другое",
  };

  if ((SUPPORT_TICKET_CATEGORY_VALUES as readonly string[]).includes(category)) {
    return RU[category as SupportTicketCategoryValue] ?? category;
  }
  return category;
}

export function supportTicketStatusLabel(status: string, _locale: AppLocale): string {
  const RU: Record<string, string> = {
    open: "Открыто",
    in_progress: "В работе",
    waiting_user: "Ожидает пользователя",
    escalated: "Эскалировано",
    closed: "Закрыто",
  };
  return RU[status] ?? status;
}
