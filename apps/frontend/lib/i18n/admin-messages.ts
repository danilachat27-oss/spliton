export function formatRoleUserCountForLocale(count: number, locale: AppLocale = "ru"): string {
  let templateKey: string;
  if (locale === "ru") {
    const mod10 = count % 10;
    const mod100 = count % 100;
    if (mod100 >= 11 && mod100 <= 14) templateKey = "admin.roleUserCount.many";
    else if (mod10 === 1) templateKey = "admin.roleUserCount.one";
    else if (mod10 >= 2 && mod10 <= 4) templateKey = "admin.roleUserCount.few";
    else templateKey = "admin.roleUserCount.many";
  } else {
    templateKey = count === 1 ? "admin.roleUserCount.one" : "admin.roleUserCount.many";
  }
  const template = adminMsg(locale, templateKey);
  return template.replace("{count}", String(count));
}
